LAW_SECTIONS = {
    "law_constitution": ("constitution.json", 3),
    "law_labor": ("tk_articles.json", 3),
    "law_civil": ("gk_articles.json", 3),
    "law_family": ("sk.json", 3),
    "law_criminal": ("uk_articles.json", 3),
    "law_courts": ("gpk_articles.json", 3),
    "law_docs": ("zpp.json", 3),
}

LAW_QUESTIONS = [
    "Что говорит закон: {title}?",
    "Объясни норму: {title}.",
    "Дай формулировку нормы: {title}.",
]


def law_records(root: Path, limit: int = 3) -> dict[str, list[tuple[str, str]]]:
    import re

    result: dict[str, list[tuple[str, str]]] = {}
    for category, (filename, limit) in LAW_SECTIONS.items():
        path = root / filename
        if not path.exists():
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            continue
        items = []
        for article in data.get("articles", []):
            text = re.sub(r"\{\{[^{}]*\}\}", " ", str(article.get("text", "")))
            text = re.sub(r"<[^>]+>", " ", text)
            text = re.sub(r"\s+", " ", text).strip()
            if len(text) < 220:
                continue
            number = article.get("number")
            heading = str(article.get("heading") or "").strip()
            title = f"статья {number}" + (f" «{heading}»" if heading else "")
            answer = (f"Дословно: «{text[:700]}». Это правовая информация, "
                      "а не консультация — сверьте редакцию на момент применения.")
            question = LAW_QUESTIONS[len(items) % len(LAW_QUESTIONS)].format(title=title)
            items.append((question, answer))
            if len(items) >= limit:
                break
        if items:
            result[category] = items
    return result


